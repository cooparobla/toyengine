"""The mesh writer against the mesh already in the tree, byte for byte.

`assets/meshes/water/water_grid.yaml` was generated by `tools/gen_water_grid_mesh.py`. If
`Mesh` is going to replace that generator and the one in `tools/mesh_yaml.py`, re-emitting the
same geometry has to produce the same file -- otherwise adopting the library rewrites every
committed mesh and buries the real change in whitespace.

This is also what pins the two number formats down: the same `Mesh` emits
`gen_water_grid_mesh.py`'s spelling with `fmt_num` and `mesh_yaml.py`'s with `fmt_g6`, and the
test proves which is which rather than trusting either file's docstring (`mesh_yaml.py`'s is
wrong about it).
"""

import pathlib

import pytest

from toyproject import Mesh, fmt_g6, fmt_num

GRID_SIZE = 12          # tools/gen_water_grid_mesh.py's own constant
ENGINE = pathlib.Path(__file__).resolve().parents[2]
COMMITTED = ENGINE / "assets/meshes/water/water_grid.yaml"


def water_grid():
    """The water grid exactly as `tools/gen_water_grid_mesh.py` builds it."""
    n = GRID_SIZE
    verts, normals, uvs, tangents = [], [], [], []
    for j in range(n + 1):
        for i in range(n + 1):
            x = -1.0 + 2.0 * i / n
            y = -1.0 + 2.0 * j / n
            verts.append([round(x, 6), round(y, 6), 0.0])
            normals.append([0.0, 0.0, 1.0])
            uvs.append([round(i / n, 6), round(j / n, 6)])
            tangents.append([1.0, 0.0, 0.0, 1.0])

    def idx(i, j):
        return j * (n + 1) + i

    faces = []
    for j in range(n):
        for i in range(n):
            faces.append([idx(i, j), idx(i + 1, j), idx(i + 1, j + 1), idx(i, j + 1)])

    return Mesh(verts, faces, uvs, normals=normals, tangents=tangents)


@pytest.mark.skipif(not COMMITTED.is_file(), reason="run from an engine checkout")
def test_regenerating_the_committed_water_grid_is_byte_identical():
    assert water_grid().to_text(fmt_num) == COMMITTED.read_text()


def test_the_two_formats_differ_exactly_where_documented():
    as_num = water_grid().to_text(fmt_num)
    as_g6 = water_grid().to_text(fmt_g6)
    assert as_num != as_g6
    # The only difference is whether a whole number keeps its ".0".
    assert "  - [-1.0, -1.0, 0.0]" in as_num
    assert "  - [-1, -1, 0]" in as_g6
    # Everything structural is the same in both.
    assert as_num.count("\n") == as_g6.count("\n")
    for key in ("vertices:", "normals:", "uvs:", "faces:", "colors: []", "weights:",
                "tangents:"):
        assert key in as_num and key in as_g6


def test_the_empty_skinning_placeholder_keeps_its_two_inner_spaces():
    # Both original writers emitted "{  }". Collapsing it to "{}" would diff every vertex.
    assert "  - {  }" in water_grid().to_text()
