# ---------------------------------------------------------------------------------------------
# Clips: hoof paths -> two-bone angles
# ---------------------------------------------------------------------------------------------

def rot_x(v, deg):
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    return (v[0], v[1] * c - v[2] * s, v[1] * s + v[2] * c)


def ang(v):
    """Angle of a (y, z) vector, measured so that rotating by +a about X adds a."""
    return math.degrees(math.atan2(v[2], v[1]))


def solve_leg(kind, side, hip_body, target_body):
    """Upper / lower X angles putting the fetlock (hoof joint) at target_body (both in the body
    frame). Fore knees bend forward, hind hocks back."""
    knee_v = FORE_KNEE if kind == "fore" else HIND_HOCK
    fet_v = FORE_FETLOCK if kind == "fore" else HIND_FETLOCK
    l1 = math.hypot(knee_v[1], knee_v[2])
    l2 = math.hypot(fet_v[1], fet_v[2])
    v = (0, target_body[1] - hip_body[1], target_body[2] - hip_body[2])
    d = min(max(math.hypot(v[1], v[2]), abs(l1 - l2) + 1e-4), l1 + l2 - 1e-4)
    alpha = math.degrees(math.acos(max(-1.0, min(1.0, (l1 * l1 + d * d - l2 * l2) / (2 * l1 * d)))))
    base = ang(v)
    # Rotating the hip->hoof line by +alpha swings the knee toward +Y (forward) for a leg
    # pointing down: fore knees forward, hind hocks back.
    knee_ang = base + (alpha if kind == "fore" else -alpha)
    knee = (0, l1 * math.cos(math.radians(knee_ang)), l1 * math.sin(math.radians(knee_ang)))
    a1 = knee_ang - ang(knee_v)
    lower = (0, v[1] - knee[1], v[2] - knee[2])
    a2 = ang(lower) - ang(fet_v) - a1
    return a1, a2


def wrap180(a):
    return (a + 180.0) % 360.0 - 180.0


def gait_clip(name, length, duty, stride, lift_fore, lift_hind, phases, bob, bob_freq, pitch, neck_nod, tail_sway):
    """A gait: `phases` = {leg: phase offset}, each hoof planted for `duty` of the cycle, sliding
    back `stride` metres, then swinging forward in an arc. Returns the ground speed (m/s)."""
    frames = round(length * FPS)
    speed = stride / (duty * length)
    tracks = {}

    def body_pose(p):
        z = BODY_Z + bob * math.cos(2 * math.pi * bob_freq * p)
        pt = pitch * math.sin(2 * math.pi * p)
        return z, pt

    def hoof_target(kind, p):
        """Root-relative hoof (fetlock) position at phase p for this leg."""
        rest_y = (FORE_HIP[1] + FORE_KNEE[1] + FORE_FETLOCK[1]) if kind == "fore" else \
                 (HIND_HIP[1] + HIND_HOCK[1] + HIND_FETLOCK[1])
        lift = lift_fore if kind == "fore" else lift_hind
        if p < duty:
            y = rest_y + stride / 2 - stride * (p / duty)
            z = HOOF_Z
            curl = 0.0
        else:
            s = (p - duty) / (1 - duty)
            e = s * s * (3 - 2 * s)
            y = rest_y - stride / 2 + stride * e
            z = HOOF_Z + lift * math.sin(math.pi * s)
            curl = math.sin(math.pi * s)
        return y, z, curl

    def reach_limited(p, bz, bp):
        """The body dropped (never raised) so every planted hoof is within its leg's reach."""
        for kind in ("fore", "hind"):
            knee_v = FORE_KNEE if kind == "fore" else HIND_HOCK
            fet_v = FORE_FETLOCK if kind == "fore" else HIND_FETLOCK
            reach = 0.985 * (math.hypot(knee_v[1], knee_v[2]) + math.hypot(fet_v[1], fet_v[2]))
            hip = FORE_HIP if kind == "fore" else HIND_HIP
            for side in "lr":
                y, z, _ = hoof_target(kind, (p + phases[f"{kind}_{side}"]) % 1.0)
                hip_root = rot_x((0, hip[1], hip[2]), bp)
                dy = y - hip_root[1]
                if abs(dy) >= reach:
                    continue
                max_hip_z = z + math.sqrt(reach * reach - dy * dy)
                bz = min(bz, max_hip_z - hip_root[2])
        return bz

    keys = {}
    for i in range(frames + 1):
        p = (i % frames) / frames
        t = i / FPS
        bz, bp = body_pose(p)
        bz = reach_limited(p, bz, bp)
        keys.setdefault(("body", "position.z"), []).append((t, round(bz, 5)))
        keys.setdefault(("body", "rotation_quat"), []).append((t, gm.quat_xyz(bp)))
        for kind in ("fore", "hind"):
            for side in "lr":
                lp = (p + phases[f"{kind}_{side}"]) % 1.0
                y, z, curl = hoof_target(kind, lp)
                hip_local = FORE_HIP if kind == "fore" else HIND_HIP
                # The target in the body frame: undo the body's height and pitch.
                rel = (0, y, z - bz)
                rel = rot_x(rel, -bp)
                a1, a2 = solve_leg(kind, side, (0, hip_local[1], hip_local[2]), rel)
                # The hoof stays level on the ground and curls back in the swing.
                a3 = -(a1 + a2 + bp) - (55 if kind == "fore" else 35) * curl
                base = f"body/{kind}_upper_{side}"
                keys.setdefault((base, "rotation_quat"), []).append((t, gm.quat_xyz(a1)))
                keys.setdefault((f"{base}/{kind}_lower_{side}", "rotation_quat"), []).append((t, gm.quat_xyz(a2)))
                keys.setdefault((f"{base}/{kind}_lower_{side}/{kind}_hoof_{side}", "rotation_quat"), []).append(
                    (t, gm.quat_xyz(a3)))
        keys.setdefault(("body/neck", "rotation_quat"), []).append(
            (t, gm.quat_xyz(neck_nod * math.sin(2 * math.pi * bob_freq * p + 0.6) - bp)))
        keys.setdefault(("body/neck/head", "rotation_quat"), []).append(
            (t, gm.quat_xyz(-0.5 * neck_nod * math.sin(2 * math.pi * bob_freq * p + 0.6))))
        keys.setdefault(("body/tail", "rotation_quat"), []).append(
            (t, gm.quat_xyz(-10 - 0.5 * pitch * math.sin(2 * math.pi * p), tail_sway * math.sin(2 * math.pi * p), 0)))
    for (path, prop), ks in keys.items():
        if prop == "rotation_quat":
            ks = hemisphere(ks)
        tracks[(path, prop)] = ks
    gm.write_clip(name, length, [(path, prop, ks, "linear") for (path, prop), ks in tracks.items()],
                  anim_dir=ANIM_DIR, label="horse")
    return speed


def hemisphere(keys):
    out, prev = [], None
    for t, q in keys:
        if prev is not None and sum(a * b for a, b in zip(q, prev)) < 0:
            q = [-c for c in q]
        prev = q
        out.append((t, [round(c, 6) for c in q]))
    return out


def idle_clip():
    length, n = 3.0, 12
    tau = 2 * math.pi
    tracks = [
        ("body", "position.z", [(length * i / n, round(BODY_Z - 0.006 * (1 - math.sin(tau * i / n)), 5)) for i in range(n + 1)], "linear"),
        ("body/neck", "rotation_quat", hemisphere([(length * i / n, gm.quat_xyz(-4 + 4 * math.sin(tau * i / n))) for i in range(n + 1)]),
         "ease_in_out"),
        ("body/neck/head", "rotation_quat",
         hemisphere([(length * i / n, gm.quat_xyz(3 * math.sin(tau * i / n + 1.0), 0, 6 * math.sin(tau * i / n * 0.5 * 2)))
                     for i in range(n + 1)]), "ease_in_out"),
        ("body/tail", "rotation_quat",
         hemisphere([(length * i / n, gm.quat_xyz(-12, 18 * math.sin(2 * tau * i / n) * (1 if i < n // 2 else 0.3), 0))
                     for i in range(n + 1)]), "ease_in_out"),
    ]
    # Standing: each hoof planted under its hip (the legs have slack, so this bends them a touch).
    for kind in ("fore", "hind"):
        hip = FORE_HIP if kind == "fore" else HIND_HIP
        knee_v = FORE_KNEE if kind == "fore" else HIND_HOCK
        fet_v = FORE_FETLOCK if kind == "fore" else HIND_FETLOCK
        rest_y = hip[1] + knee_v[1] + fet_v[1]
        for side in "lr":
            a1, a2 = solve_leg(kind, side, (0, hip[1], hip[2]), (0, rest_y, HOOF_Z - BODY_Z))
            base = f"body/{kind}_upper_{side}"
            for path, a in ((base, a1), (f"{base}/{kind}_lower_{side}", a2),
                            (f"{base}/{kind}_lower_{side}/{kind}_hoof_{side}", -(a1 + a2))):
                q = [round(c, 6) for c in gm.quat_xyz(a)]
                tracks.append((path, "rotation_quat", [(0.0, q), (length, q)], "linear"))
    gm.write_clip("idle", length, tracks, anim_dir=ANIM_DIR, label="horse")


