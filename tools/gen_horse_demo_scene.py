#!/usr/bin/env python3
"""Writes assets/scenes/gameplay/horse_demo: walk up to a horse, get on, ride it, get off.

Outputs (under the scene folder):
  * scene.yaml -- the player (a mannequin_ik with a CharacterController, CharacterAnimDriver,
    FootIK and a Rider), two horses (objects/animals/horse: a Mount, a four-legged FootIK), an
    orbit camera that follows whichever is ridden, a paddock with a gate, a low step row, a ramp
    and a rolling hill patch to ride over.
  * meshes/horse_hills.yaml + horse_hills_collider.yaml -- the hill patch (render mesh and its
    MeshCollider copy).

Run:  python3 tools/gen_horse.py && python3 tools/gen_horse_demo_scene.py   then
      ./build/toyengine horse_demo
"""

import math
import os
import pathlib
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mesh_yaml  # noqa: E402
from gen_character_demo_scene import block, num, ramp, tint, v3  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "scenes", "gameplay", "horse_demo")
GENERATED = "GENERATED by tools/gen_horse_demo_scene.py; edit that, not this file."

GRASS = "{ albedo: { r: 0.36, g: 0.5, b: 0.24 }, roughness: 0.95 }"
DIRT = "{ albedo: { r: 0.48, g: 0.38, b: 0.26 }, roughness: 0.9 }"
WOOD = "{ albedo: { r: 0.45, g: 0.32, b: 0.2 }, roughness: 0.75 }"
STONE = tint(0.62, 0.6, 0.56)

HILLS_AT = (0.0, 34.0)   # the hill patch's centre
HILLS_SIZE = 30.0


def hills_mesh():
    """A 30 x 30 m patch of rolling hills (slopes under ~25 degrees), zero at its rim."""
    n, size = 48, HILLS_SIZE
    verts, uvs, faces = [], [], []
    for j in range(n + 1):
        for i in range(n + 1):
            x = -size / 2 + size * i / n
            y = -size / 2 + size * j / n
            u, v = i / n, j / n
            w = math.sin(math.pi * u) * math.sin(math.pi * v)
            f = 0.55 + 0.45 * math.sin(0.32 * x + 0.5) * math.cos(0.28 * y - 0.2)
            f = 0.8 * f + 0.2 * (0.5 + 0.5 * math.sin(0.6 * x + 0.45 * y))
            verts.append([round(x, 5), round(y, 5), round(0.01 + 3.2 * w * f, 5)])
            uvs.append([round(x * 0.5, 5), round(y * 0.5, 5)])
    row = n + 1
    for j in range(n):
        for i in range(n):
            a = j * row + i
            faces.append([a, a + 1, a + row + 1, a + row])
    os.makedirs(os.path.join(ROOT, "meshes"), exist_ok=True)
    r5 = lambda vs: [[round(c, 5) for c in v] for v in vs]
    normals = r5(mesh_yaml.vertex_normals(verts, faces))
    mesh_yaml.write_mesh(pathlib.Path(ROOT, "meshes", "horse_hills.yaml"), verts, faces, uvs, normals=normals,
                         tangents=r5(mesh_yaml.perpendicular_tangents(normals)))
    with open(os.path.join(ROOT, "meshes", "horse_hills_collider.yaml"), "w") as fh:
        fh.write(f"# Collision copy of horse_hills (a MeshCollider needs its own file). {GENERATED}\n")
        fh.write("vertices:\n" + "".join(f"  - {mesh_yaml.fmt_vec(p)}\n" for p in verts))
        fh.write("faces:\n" + "".join(f"  - {f}\n" for f in faces))
    return verts, n


def hill_height(verts, n, x, y):
    """The patch's height under world (x, y) (nearest vertex; good enough to seat a horse)."""
    size = HILLS_SIZE
    i = round((x - HILLS_AT[0] + size / 2) / size * n)
    j = round((y - HILLS_AT[1] + size / 2) / size * n)
    i, j = max(0, min(n, i)), max(0, min(n, j))
    return verts[j * (n + 1) + i][2]


HEADER = f"""# horse_demo -- riding: walk up to a horse, get on, ride it through walk / trot / gallop, get off.
# {GENERATED}
#
# Run: ./build/toyengine horse_demo        (or SCENE=horse_demo)
# On foot: WASD move (camera-relative), Space jump, LeftShift sprint, mouse orbits, scroll zooms.
# F next to a horse (either side of the saddle) gets on; F again gets off on a clear side.
# Riding: WASD steers (camera-relative: the horse turns toward that way at a limited rate and
# always moves along its own facing), input alone trots, LeftShift gallops, LeftControl walks,
# Space jumps; let go to stop. The camera follows the horse while ridden.
#
# Map (the player starts at the origin facing +Y):
#   x =  2.2  horse          standing beside the start, facing +Y (its left side toward you)
#   y =  8..30 paddock       a fenced field; the gate gap in its south side is straight ahead of the horse
#   x = -12  step row        three 0.2 m steps: the hooves plant on each (four-leg FootIK)
#   x =  12  ramp            a 12 degree ramp up to a 1.2 m plateau and down the far side
#   y =  34  hills           a 30 x 30 m rolling MeshCollider patch; horse_hill stands on a slope
#                            there with its hooves planted and its body pitched (FootIK body_pitch)
#
# How it fits together (toyengine/scene/mount.h, rider.h):
#   * The horse is a CharacterController (player_input: false) steered by its Mount, which picks
#     the gait from its speed and plays the gait clip at speed / gait speed (no hoof sliding).
#   * The player's Rider suspends its CharacterController and FootIK, crossfades to `ride`, and
#     each frame (an IK driver, after the Animator) seats the rig on the saddle; its leg / arm
#     TwoBoneIKs reach for the stirrups and reins, its spine leans into a gallop.
#   * FootIK on the horse runs four legs: each hoof is raised / lowered onto the ground under it,
#     and the body rises / drops and pitches between front and hind.
"""


def horse(name, pos, yaw, comment):
    return [f"    # {comment}",
            f"    - name: {name}",
            "      prefab: objects/horse",
            "      components:",
            "        - type: Transform",
            f"          position: {v3(*pos)}",
            f"          rotation: {v3(0, 0, yaw)}",
            f"          scale: {v3(1, 1, 1)}",
            ""]


def fence(L, x0, x1, y0, y1, gate=None):
    """A post-and-rail fence round the rectangle, with a `gate` (x_from, x_to) gap on the y0 side."""
    post_gap = 3.0
    rail = WOOD

    def run(name, a, b, fixed, along_x):
        length = b - a
        posts = max(1, round(length / post_gap))
        for k in range(posts + 1):
            t = a + length * k / posts
            p = (t, fixed) if along_x else (fixed, t)
            L.extend(block(f"{name}_post_{k}", (p[0], p[1], 0.6), (0.18, 0.18, 1.2), rail))
        mid = (a + b) / 2
        for h, z in (("hi", 1.05), ("lo", 0.6)):
            size = (length, 0.08, 0.12) if along_x else (0.08, length, 0.12)
            p = (mid, fixed) if along_x else (fixed, mid)
            L.extend(block(f"{name}_rail_{h}", (p[0], p[1], z), size, rail))

    L.append("    # The paddock fence: posts and two rails (all static colliders); the gate gap is south.")
    if gate:
        run("fence_s1", x0, gate[0], y0, True)
        run("fence_s2", gate[1], x1, y0, True)
    else:
        run("fence_s", x0, x1, y0, True)
    run("fence_n", x0, x1, y1, True)
    run("fence_w", y0, y1, x0, False)
    run("fence_e", y0, y1, x1, False)


def main():
    verts, n = hills_mesh()
    L = [HEADER.rstrip("\n"), "scene:", "  scene_name: horse_demo",
         "  settings:",
         "    weather:",
         "      enabled: true",
         "      time_of_day: 9.5",
         "      day_length_minutes: 30",
         "      drive_sun: true",
         "      condition: clear",
         "      schedule: fixed",
         "  root_objects:"]

    L += [
        "    # Ground: a 200 x 200 m field, its top at z = 0.",
        "    - name: ground",
        "      components:",
        "        - type: Transform",
        f"          position: {v3(0, 0, -0.25)}",
        f"          rotation: {v3(0, 0, 0)}",
        f"          scale: {v3(200, 200, 0.5)}",
        "        - type: MeshRenderer",
        "          mesh_path: cube",
        f"          material: {GRASS}",
        "        - type: BoxCollider",
        "          size: { x: 1.0, y: 1.0, z: 1.0 }",
        "      children: []",
        "",
    ]

    L += [
        "    # The player: the fully IK mannequin (its leg / arm TwoBoneIKs are what reach for the",
        "    # stirrups and reins) with a CharacterController, the idle/walk/run/jump driver, FootIK on",
        "    # foot, and a Rider: F near a horse's mount point gets on, F again gets off.",
        "    - name: player",
        "      prefab: objects/mannequin_ik",
        "      components:",
        "        - type: Transform",
        f"          position: {v3(0, 0, 0)}",
        f"          rotation: {v3(0, 0, 0)}",
        f"          scale: {v3(1, 1, 1)}",
        "        - type: CharacterController",
        "          radius: 0.3",
        "          height: 1.8",
        "          move_speed: 3.0",
        "          sprint_multiplier: 2.0",
        "          jump_height: 1.2",
        "          use_root_motion: true",
        "        - type: Animator",
        "          apply_root_motion: true",
        "        - type: CharacterAnimDriver",
        "          walk_speed: 0.2",
        "          run_speed: 4.0",
        "          crossfade: 0.2",
        "        - type: FootIK",
        "          ray_up: 0.45",
        "          ray_down: 0.4",
        "        - type: Rider",
        "          mount_radius: 1.6",
        "          mount_time: 0.8",
        "          dismount_time: 0.6",
        "          ride_state: ride",
        "",
    ]

    L += horse("horse", (2.2, 0.8, 0), 0, "The horse: get on from either side of the saddle (F). Its left side faces the start.")
    hx, hy = HILLS_AT[0] - 5.0, HILLS_AT[1] - 3.0
    L += horse("horse_hill", (hx, hy, hill_height(verts, n, hx, hy) + 0.05), 30,
               "A second horse standing on the hills' slope: hooves planted, body pitched by FootIK.")

    # The paddock with a south gate.
    fence(L, -8.0, 8.0, 8.0, 30.0, gate=(0.2, 4.2))   # the gate in line with the horse
    L += block("paddock_track", (0, 19, 0.005), (14.0, 20.0, 0.01), DIRT,
               comment="A dirt track inside the paddock (just a look; flush with the ground).")

    # Step row: three 0.2 m steps for the hooves.
    for i in range(3):
        h = 0.2 * (i + 1)
        L += block(f"step_{i + 1}", (-12, 6 + 1.6 * i + 0.8, h / 2), (5.0, 1.6, h), STONE,
                   comment="Step row: 0.2 m risers (under the horse's step_height 0.4); hooves plant on each." if i == 0 else None)
    L += block("step_top", (-12, 6 + 4.8 + 2.0, 0.3), (5.0, 4.0, 0.6), STONE)

    # Ramp up to a plateau and down the far side.
    ang, rlen, plat_h = 12.0, 1.2 / math.sin(math.radians(12.0)), 1.2
    L += ramp("ramp_up", 12, 4, ang, rlen, 4.0, STONE, f"Ramp: {num(ang)} degrees up to a {num(plat_h)} m plateau.")
    run_y = rlen * math.cos(math.radians(ang))
    L += block("plateau", (12, 4 + run_y + 3.0, plat_h / 2), (4.0, 6.0, plat_h), STONE)
    # The far side down: the same ramp mirrored (rising toward -Y).
    t = math.radians(ang)
    y_far = 4 + run_y + 6.0 + run_y
    cy = y_far - 0.5 * rlen * math.cos(t) - 0.1 * math.sin(t)
    cz = 0.5 * rlen * math.sin(t) - 0.1 * math.cos(t)
    L += block("ramp_down", (12, cy, cz), (4.0, rlen, 0.2), STONE, rot=(-ang, 0, 0))

    L += [
        "    # Hills: a rolling 30 x 30 m heightfield on a static MeshCollider.",
        "    - name: hills",
        "      components:",
        "        - type: Transform",
        f"          position: {v3(HILLS_AT[0], HILLS_AT[1], 0)}",
        f"          rotation: {v3(0, 0, 0)}",
        f"          scale: {v3(1, 1, 1)}",
        "        - type: MeshRenderer",
        "          mesh_path: horse_hills",
        f"          material: {GRASS}",
        "        - type: MeshCollider",
        "          mesh_path: horse_hills_collider",
        "          convex: false",
        "      children: []",
        "",
    ]

    L += [
        "    # Third-person camera: orbits the player (the horse while ridden -- the Rider re-points",
        "    # `tracker` and uses the Mount's camera offset / distance) and collides.",
        "    - name: camera",
        "      components:",
        "        - type: Transform",
        f"          position: {v3(-2, -7, 3.8)}",
        f"          rotation: {v3(65, 0, 0)}",
        f"          scale: {v3(1, 1, 1)}",
        "        - type: Camera",
        "          main: true",
        "          projection: Perspective",
        "          fov: 60.0",
        "          near_clip_plane: 0.1",
        "          far_clip_plane: 500.0",
        "        - type: CameraController",
        "          mode: orbit",
        "          tracker: player",
        f"          target_offset: {v3(0, 0, 1.4)}",
        "          follow_smoothing: 12.0",
        "          movement_smoothing: 0.2",
        "          mouse_sensitivity: 0.12",
        "          distance: 7.5",
        "          yaw_deg: -15.0",
        "          pitch_deg: 20.0",
        "          min_pitch_deg: -10.0",
        "          max_pitch_deg: 80.0",
        "          min_distance: 1.5",
        "          max_distance: 20.0",
        "          collide: true",
        "          collision_radius: 0.25",
        "      children: []",
        "",
        "    - name: sun",
        "      components:",
        "        - type: Transform",
        f"          position: {v3(0, 0, 20)}",
        f"          rotation: {v3(0, 0, 0)}",
        f"          scale: {v3(1, 1, 1)}",
        "        - type: DirectionalLight",
        f"          direction: {v3(-0.45, 0.55, -0.7)}",
        "          color: { r: 1.0, g: 0.96, b: 0.9 }",
        "          intensity: 1.0",
        "          cast_shadows: true",
        "      children: []",
    ]
    os.makedirs(ROOT, exist_ok=True)
    with open(os.path.join(ROOT, "scene.yaml"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", os.path.join(ROOT, "scene.yaml"))


if __name__ == "__main__":
    main()
