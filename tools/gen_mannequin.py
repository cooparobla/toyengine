#!/usr/bin/env python3
"""Writes the `mannequin`: a humanoid object-hierarchy rig, its capsule part meshes and its clips.

Outputs (all under assets/):
  * objects/characters/mannequin.yaml -- the rig as an OBJECT ASSET (prefab). Place it with
    `prefab: objects/mannequin`; add a CharacterController (+ CharacterAnimDriver) to the
    instance to make it a player (see scenes/gameplay/character_demo).
  * objects/characters/mannequin_ragdoll.yaml -- the same rig plus a Ragdoll (capsule/box bones,
    cone-twist hips/shoulders/spine/neck, hinge knees/elbows/ankles; see RAGDOLL below and
    toyengine/scene/ragdoll.h). A separate prefab, so plain mannequins carry no bone bodies.
  * objects/characters/mannequin_ik.yaml -- the same rig FULLY IK-driven: no clip touches a
    bone. Its clips (animations/mannequin_ik/) key only target empties -- foot / hand targets,
    knee / elbow poles, a chest target, a look target -- and IK poses every bone from them:
    TwoBoneIK legs and arms (match_target_rotation), a ChainIK spine, a LookAtIK head. The IK
    clips are BAKED from the keyframed ones (forward kinematics, every frame), so it moves like
    the plain mannequin; FootIK on it adjusts the foot targets (mode auto -> targets).
  * meshes/characters/mannequin_*.yaml -- one capsule mesh per body part (Z-up, centred).
  * animations/mannequin/{idle,walk,run,jump}.yaml -- the clips its Animator plays. walk and run
    carry ROOT MOTION (the pelvis's travel, `root_motion: {object: pelvis, translation: xy}`) and
    `footstep` events (string left / right) as each foot plants.
  * animations/mannequin_ik/{idle,walk,run,jump}.yaml -- the same motion as target tracks.

The rig, Z-up and facing local +Y (its right hand is +X, its left -X), origin at the feet,
about 1.8 m tall -- the default CharacterController capsule (radius 0.3, height 1.8):

  mannequin                      Animator (idle / walk / run / jump)
    pelvis                       z 0.95
      spine                        abdomen
        chest                      torso
          neck
            head                   head + visor (the visor marks the front)
          upper_arm_l / _r         shoulders at x -/+0.21
            lower_arm_l / _r
              hand_l / _r
      thigh_l / _r                 hips at x -/+0.1
        shin_l / _r
          foot_l / _r

Joints are empty objects at their pivots with identity rest rotations; limbs hang along local
-Z, so a positive X rotation swings a limb FORWARD (+Y) and a negative one bends a knee back.
Each visible part is a child `<joint>_shape` of its joint. These names are the rig's contract:
clips address joints by path, and later systems (foot IK, ragdoll bone lists) name them too.

Run:  python3 tools/gen_mannequin.py
"""

