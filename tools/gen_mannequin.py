def ik_rig():
    """RIG with the upper-body target empties added under the pelvis, at their rest places."""
    rest_world = fk_pose({"tracks": [], "root_motion": None}, 0.0)
    rest = ik_targets(rest_world)
    pelvis_p = rest_world["pelvis"][0]
    extra = [joint(obj, tuple(round(rest[obj][0][k] - pelvis_p[k], 5) for k in range(3)), [])
             for obj in IK_TARGET_NAMES if obj in UPPER_BODY_TARGETS]
    return dict(RIG, children=RIG["children"] + extra)


def ik_target_children():
    """The feet's and knees' target empties: children of the mannequin root, at their rest places."""
    rest = ik_targets(fk_pose({"tracks": [], "root_motion": None}, 0.0))
    out = []
    for obj in IK_TARGET_NAMES:
        if obj in UPPER_BODY_TARGETS:
            continue
        p = rest[obj][0]
        out += [f"    - name: {obj}",
                "      components:",
                "        - type: Transform",
                f"          {vec('position', [round(c, 5) for c in p])}",
                "          rotation: {x: 0, y: 0, z: 0}",
                "      children: []"]
    return out


