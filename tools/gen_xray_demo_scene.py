"""Generates assets/scenes/rendering/xray_demo/scene.yaml -- the see-through bench.

Standalone generator, not part of the C++ build -- run it manually
(`python3 tools/gen_xray_demo_scene.py`) and commit the result.

Two features share one scene because they answer the same question from opposite ends: what
happens when something comes between the camera and the player.

  * X-ray silhouettes (`xray_enabled`, XraySubject / XrayOccluder): the player shows through
    whatever is flagged see-through-able, and stays hidden behind whatever is not.
  * ViewBlockerFade: a wall whose collider is in the way erodes itself out of the shot.

**Both are visible from the first frame, and the geometry is what makes that true.** At a
top-down pitch the line from camera to player descends steeply, so it clears anything short
that is not very close to the player -- the demo's first draft put the fade walls 11 m behind
the player, which is BEHIND the camera, where they could never block anything. Measured for
this scene's rig (distance 16, pitch 50, target 1 m up), the sightline sits at:

    y = -5.0  ->  z = 7.06        y = -2.0  ->  z = 3.54
    y = -4.0  ->  z = 5.89        y = -1.5  ->  z = 2.96
    y = -3.0  ->  z = 4.72        y = -1.0  ->  z = 2.37

So a blocker must be taller than that at its own distance. Hence the layout: a ROOF, which is
horizontal and therefore always crosses the line (the x-ray station), and POSTS set close in
front of the player and tall enough to reach it (the fade station). Reposition anything here
and re-check it against that table, or the station silently stops demonstrating.
"""

import math
import pathlib

OUTPUT_PATH = pathlib.Path(__file__).resolve().parent.parent / "assets" / "scenes" / "rendering" / "xray_demo" / "scene.yaml"
"""Where the generated scene is written; resolved relative to this repo, not the caller's cwd."""

GRID = "materials/prototype_grid"
"""Shared base material for the blockout geometry, so nothing here needs its own asset."""

CAM_DISTANCE = 16.0
CAM_PITCH_DEG = 50.0
"""The orbit rig. Shallower than a strict overhead view so blockers of a believable height can
reach the sightline at all -- see the module doc's table."""

DISSOLVE_MASK = "textures/masks/dissolve_noise.png"
"""Noise in the ALPHA channel, minimum 0.06 so `alpha_cutoff: 0` leaves no pinholes (see
tools/gen_dissolve_noise.py)."""


def sightline_z(y: float) -> float:
    """Height of the camera-to-player line above the ground at world `y`.

    Args:
        y: World y to sample, between the camera and the player (negative).

    Returns:
        float: The line's z there. A blocker at this y must exceed it to block the view.
    """
    e = math.radians(CAM_PITCH_DEG)
    cam_y = -CAM_DISTANCE * math.cos(e)
    cam_z = CAM_DISTANCE * math.sin(e) + 1.0
    t = (y - cam_y) / (0.0 - cam_y)
    return cam_z + t * (1.2 - cam_z)


HEADER = """\
# xray_demo -- the see-through bench: the player's silhouette showing through geometry, and
# walls that erode out of the way of the shot.
# GENERATED by tools/gen_xray_demo_scene.py; edit that, not this file.
#
# Run: ./build/toyengine xray_demo            (or SCENE=xray_demo)
# Controls: WASD move (camera-relative), Space jump, hold RIGHT mouse to orbit, scroll zooms.
#
# BOTH EFFECTS ARE ON SCREEN AT THE START -- you do not have to go looking for them:
#
#   * The player stands under a PAVILION ROOF carrying XrayOccluder, so its silhouette is
#     showing through the roof from frame one. Walk out from under it (any direction) and the
#     silhouette gives way to the real player.
#   * Two POSTS stand just in front of the player, each carrying ViewBlockerFade. Whichever is
#     in the line of sight has already eroded through the noise mask. Orbit with the right
#     mouse button and watch them dissolve and come back as they cross the sightline.
#     Their SHADOWS stay put while they do (keep_shadow) -- the posts have not gone anywhere.
#
# Then walk to the stations:
#
#   y =  14  see-through ridge   XrayOccluder: tall enough to hide the player at this pitch
#   x = -10  SOLID pavilion      a second roof with NO XrayOccluder -- the control. Stand under
#                                it and the player really does disappear
#   x =  10  post pair, no fade  the same two posts WITHOUT ViewBlockerFade: they stay solid
#                                and simply block the view, which is the problem being solved
#
# The look is per-scene (settings.render below), not per-object: xray_mode picks silhouette /
# outline / both, and xray_color / xray_thickness / xray_depth_fade style it. Try
# `xray_mode: outline`, or raise xray_depth_fade to make depth read.
"""


def transform(pos, scale, rot=(0, 0, 0)):
    """Builds a Transform component block.

    Args:
        pos: (x, y, z) world position.
        scale: (x, y, z) world scale.
        rot: (x, y, z) Euler rotation in degrees.

    Returns:
        str: The component's YAML lines, indented 8 spaces.
    """
    return (f"        - type: Transform\n"
            f"          position: {{ x: {pos[0]}, y: {pos[1]}, z: {pos[2]} }}\n"
            f"          rotation: {{ x: {rot[0]}, y: {rot[1]}, z: {rot[2]} }}\n"
            f"          scale: {{ x: {scale[0]}, y: {scale[1]}, z: {scale[2]} }}\n")


def block(name, pos, scale, albedo, extra="", collider=True, comment=""):
    """Builds a plain cube object: Transform, MeshRenderer, BoxCollider.

    Args:
        name: Object name in the scene.
        pos: (x, y, z) centre.
        scale: (x, y, z) size.
        albedo: (r, g, b) tint over the shared grid material.
        extra: Extra component YAML (already indented 8 spaces).
        collider: Whether to add a BoxCollider.
        comment: Comment line placed above the object.

    Returns:
        str: The object's YAML block.
    """
    out = comment
    out += f"    - name: {name}\n      components:\n"
    out += transform(pos, scale)
    out += ("        - type: MeshRenderer\n"
            "          mesh_path: cube\n"
            f"          material: {{ base: {GRID}, albedo: {{ r: {albedo[0]}, g: {albedo[1]}, b: {albedo[2]} }} }}\n")
    if collider:
        out += ("        - type: BoxCollider\n"
                "          size: { x: 1.0, y: 1.0, z: 1.0 }\n")
    out += extra
    out += "      children: []\n"
    return out


def post(name, pos, height, fade, comment=""):
    """Builds one tall post -- the fade station's blocker.

    Authored CUTOUT with the dissolve mask and `alpha_cutoff: 0` whether or not it fades, so the
    two variants differ ONLY by the component and a reader can see that is the only difference.
    Switching alpha_mode at runtime is what the authoring avoids: it would change the material's
    texture key and allocate a fresh descriptor set from a pool capped at 64.

    Args:
        name: Object name.
        pos: (x, y) of the post's centre; z is derived from `height`.
        height: Post height in metres.
        fade: Whether to attach ViewBlockerFade.
        comment: Comment line placed above the object.

    Returns:
        str: The object's YAML block.
    """
    out = comment
    out += f"    - name: {name}\n      components:\n"
    out += transform((pos[0], pos[1], round(height / 2.0, 3)), (0.7, 0.7, height))
    out += ("        - type: MeshRenderer\n"
            "          mesh_path: cube\n"
            "          material:\n"
            f"            base: {GRID}\n"
            "            albedo: { r: 0.78, g: 0.70, b: 0.55 }\n"
            "            alpha_mode: CUTOUT\n"
            "            alpha_cutoff: 0.0\n"
            f"            texture_alpha_mask: {DISSOLVE_MASK}\n"
            "        - type: BoxCollider\n"
            "          size: { x: 1.0, y: 1.0, z: 1.0 }\n")
    if fade:
        out += ("        - type: ViewBlockerFade\n"
                "          fade_target: 1.0\n"
                "          fade_in_time: 0.18\n"
                "          fade_out_time: 0.35\n"
                "          keep_shadow: true\n")
    out += "      children: []\n"
    return out


def pavilion(prefix, cx, roof_z, occluder, comment=""):
    """Builds a roof slab on four corner legs.

    The roof is the x-ray station's occluder: horizontal, so it crosses the camera-to-player
    line whatever the pitch, which is what makes the silhouette visible without walking.

    Args:
        prefix: Name prefix for the parts.
        cx: World x of the pavilion's centre.
        roof_z: Height of the underside of the roof.
        occluder: Whether the roof carries XrayOccluder.
        comment: Comment line placed above the group.

    Returns:
        str: The objects' YAML blocks.
    """
    marker = "        - type: XrayOccluder\n" if occluder else ""
    out = comment
    out += block(f"{prefix}_roof", (cx, 0.0, roof_z + 0.15), (9.0, 9.0, 0.3),
                 (0.52, 0.50, 0.58) if occluder else (0.60, 0.42, 0.40), extra=marker)
    for i, (dx, dy) in enumerate(((-4.0, -4.0), (4.0, -4.0), (-4.0, 4.0), (4.0, 4.0))):
        out += block(f"{prefix}_leg_{i}", (cx + dx, dy, roof_z / 2.0), (0.5, 0.5, roof_z),
                     (0.45, 0.44, 0.48))
    return out


def build() -> str:
    """Assembles the whole scene file.

    Returns:
        str: The complete scene.yaml contents.
    """
    out = [HEADER, """
scene:
  scene_name: xray_demo
  settings:
    render:
      # The feature itself. STARTUP-FIXED: with this false the mask target is never allocated
      # and the pass is never built, so a scene that omits it pays nothing at all.
      xray_enabled: true
      # silhouette | outline | both. Every value below is a push constant, free to change
      # per frame -- flip these live in the editor's Render settings.
      xray_mode: silhouette
      xray_color: [0.25, 0.85, 1.0, 0.6]
      xray_thickness: 2.0
      # 0 draws the whole hidden area at one strength. Raise it and the silhouette dims the
      # further behind the covering surface the player walks.
      xray_depth_fade: 0.0
      outline_enabled: false
      ambient_intensity: 0.45
    physics:
      gravity: { x: 0, y: 0, z: -9.81 }
  root_objects:
"""]

    # Ground: a 60 x 60 m slab, its top at z = 0.
    out.append(block("ground", (0, 0, -0.25), (60, 60, 0.5), (0.55, 0.57, 0.6)))

    # The player. A capsule body with a head and a pack as CHILDREN, deliberately: one
    # XraySubject on the root covers the whole subtree, and the three meshes come out as a
    # single merged silhouette with a single outline rather than three stacked cut-outs --
    # which is the behaviour worth being able to see.
    #
    # Built from primitives rather than the mannequin prefab on purpose. That prefab carries
    # its own Ragdoll and Animator and expects the clips and the FootIK/Ragdoll pairing
    # character_demo gives it; dropped into this scene with only part of that rigging, it fell
    # through the floor on spawn. A render bench does not need a skeleton, and primitives keep
    # the thing being demonstrated the only moving part.
    out.append(
        "    - name: player\n"
        "      components:\n"
        + transform((0, 0, 0.9), (0.7, 0.7, 1.8)) +
        "        - type: MeshRenderer\n"
        # cube, not capsule: assets/meshes/primitives/ ships cube/sphere/plane/ball and no
        # capsule, and an unresolvable mesh_path is a silent non-draw rather than an error.
        "          mesh_path: cube\n"
        f"          material: {{ base: {GRID}, albedo: {{ r: 0.85, g: 0.32, b: 0.24 }} }}\n"
        "        - type: CharacterController\n"
        "          radius: 0.35\n"
        "          height: 1.8\n"
        "          step_height: 0.35\n"
        "          slope_limit: 45.0\n"
        "          move_speed: 4.0\n"
        "          sprint_multiplier: 1.8\n"
        "          jump_height: 1.0\n"
        "        - type: XraySubject\n"
        "      children:\n"
        "        - name: player_head\n"
        "          components:\n"
        + "  " + transform((0, 0, 0.62), (0.63, 0.63, 0.34)).replace("\n        - type", "\n          - type").replace("\n          position", "\n            position").replace("\n          rotation", "\n            rotation").replace("\n          scale", "\n            scale") +
        "          - type: MeshRenderer\n"
        "            mesh_path: sphere\n"
        f"            material: {{ base: {GRID}, albedo: {{ r: 0.92, g: 0.78, b: 0.62 }} }}\n"
        "          children: []\n"
        "        - name: player_pack\n"
        "          components:\n"
        + "  " + transform((0, 0.5, 0.15), (0.8, 0.5, 0.5)).replace("\n        - type", "\n          - type").replace("\n          position", "\n            position").replace("\n          rotation", "\n            rotation").replace("\n          scale", "\n            scale") +
        "          - type: MeshRenderer\n"
        "            mesh_path: cube\n"
        f"            material: {{ base: {GRID}, albedo: {{ r: 0.30, g: 0.45, b: 0.35 }} }}\n"
        "          children: []\n"
    )

    # --- Station 1: the pavilion over the start. Roof at 3.2 m; the sightline crosses that
    # height at y = -2.3, inside the 9 m footprint, so the player is under it from frame one.
    out.append(pavilion(
        "pavilion", 0.0, 3.2, True,
        comment="    # The pavilion over the start. Its ROOF carries XrayOccluder, and being\n"
                "    # horizontal it always crosses the camera-to-player line -- which is what puts\n"
                "    # the silhouette on screen without anyone having to walk anywhere.\n"
                "    #\n"
                "    # The fade posts below stand inside its footprint, and the overlap is wanted: as a\n"
                "    # post erodes, the roof behind it becomes the frontmost surface and the silhouette\n"
                "    # fills in where the post used to be. The two features composing is the point.\n"))

    # --- Station 2: the fade posts, close in and tall enough to reach the sightline.
    ph = 4.0
    out.append(post("fade_post_c", (0.0, -2.0), ph, True,
                    comment=f"    # The fade posts. Two things have to be true for one of these to be detected at\n"
                            f"    # all. It must be TALL enough: at y = -2.0 the sightline is {sightline_z(-2.0):.2f} m up, so {ph:.0f} m\n"
                            "    # posts reach it. And it must STRADDLE the line: the system's probe is a capsule of\n"
                            "    # radius 0.4 m, so a post set off to one side of the sightline is simply not in the\n"
                            "    # way and correctly does not fade. Hence one post dead ahead -- already eroded at\n"
                            "    # frame one -- and two more at +/- 3 m that come into play as the camera orbits.\n"
                            "    # Their SHADOWS stay put throughout (keep_shadow): the posts are still there.\n"))
    out.append(post("fade_post_l", (-3.0, -2.0), ph, True))
    out.append(post("fade_post_r", (3.0, -2.0), ph, True))

    # --- Controls, a short walk away.
    out.append(pavilion(
        "solid_pavilion", -10.0, 3.2, False,
        comment="    # x = -10 -- the CONTROL roof. No XrayOccluder, so standing under this one the\n"
                "    # player really does vanish. This is the station that proves occluder opt-in\n"
                "    # gates rather than decorates.\n"))
    out.append(post("fixed_post_c", (10.0, -2.0), ph, False,
                    comment="    # x = 10 -- the same post WITHOUT ViewBlockerFade. It stays solid and simply\n"
                            "    # blocks the view, which is the problem the fade exists to solve. Walk across to\n"
                            "    # it and the camera's line runs into it the same way.\n"))

    # --- Station 3: the ridge, for walking behind rather than under.
    out.append("    # y = 14 -- the see-through ridge. Tall enough to hide the player at this pitch\n"
               "    # (the sightline is well above head height that far out), so walk behind it.\n")
    for i, (x, h) in enumerate(((-6.0, 6.0), (0.0, 7.5), (6.0, 6.0))):
        out.append(block(f"ridge_{i}", (x, 14.0, h / 2.0), (6.0, 2.5, h), (0.50, 0.55, 0.52),
                         extra="        - type: XrayOccluder\n"))

    out.append(
        "    # The camera. `collide` is deliberately OFF: the stock rig pulls the camera IN when\n"
        "    # a wall blocks the player, which is the third alternative to both features on show\n"
        "    # and would hide them by solving the problem first.\n"
        "    - name: camera\n"
        "      components:\n"
        + transform((0, -10.3, 13.3), (1, 1, 1), (CAM_PITCH_DEG, 0, 0)) +
        "        - type: Camera\n"
        "          main: true\n"
        "          projection: Perspective\n"
        "          fov: 55.0\n"
        "          near_clip_plane: 0.1\n"
        "          far_clip_plane: 400.0\n"
        "        - type: CameraController\n"
        "          mode: orbit\n"
        "          tracker: player\n"
        "          target_offset: { x: 0, y: 0, z: 1.0 }\n"
        "          follow_smoothing: 12.0\n"
        "          movement_smoothing: 0.2\n"
        "          mouse_sensitivity: 0.12\n"
        f"          distance: {CAM_DISTANCE}\n"
        "          yaw_deg: 0.0\n"
        f"          pitch_deg: {CAM_PITCH_DEG}\n"
        "          min_pitch_deg: 20.0\n"
        "          max_pitch_deg: 80.0\n"
        "          min_distance: 6.0\n"
        "          max_distance: 32.0\n"
        "          collide: false\n"
        "          look_button: right\n"
        "      children: []\n"
    )

    out.append(
        "    - name: sun\n"
        "      components:\n"
        + transform((0, 0, 20), (1, 1, 1)) +
        "        - type: DirectionalLight\n"
        "          direction: { x: -0.45, y: 0.55, z: -0.7 }\n"
        "          color: { r: 1.0, g: 0.96, b: 0.9 }\n"
        "          intensity: 1.0\n"
        "          cast_shadows: true\n"
        "      children: []\n"
    )
    return "".join(out)


def main() -> None:
    """Generates the scene and writes it to OUTPUT_PATH."""
    text = build()
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(text)
    print(f"Wrote {OUTPUT_PATH} ({len(text.splitlines())} lines)")
    for y in (-1.8, -2.3, -3.0):
        print(f"  sightline at y={y}: z={sightline_z(y):.2f}")


if __name__ == "__main__":
    main()
